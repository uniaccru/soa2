CREATE TABLE cave (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    depth BIGINT NOT NULL CHECK (depth >= 0)
);

CREATE TABLE dragon (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             VARCHAR(255) NOT NULL CHECK (length(name) > 0),
    coordinates_x    INTEGER NOT NULL CHECK (coordinates_x > -42),
    coordinates_y    INTEGER NOT NULL CHECK (coordinates_y <= 9),
    creation_date    DATE NOT NULL,
    age              BIGINT CHECK (age > 0),
    description      TEXT,
    weight           INTEGER CHECK (weight > 0),
    color            VARCHAR(16) CHECK (color IN ('YELLOW', 'ORANGE', 'WHITE')),
    cave_id          BIGINT UNIQUE REFERENCES cave (id),
    killer_name      VARCHAR(255) CHECK (killer_name IS NULL OR length(killer_name) > 0),
    killer_height    DOUBLE PRECISION CHECK (killer_height IS NULL OR killer_height > 0),
    killer_eye_color VARCHAR(16) CHECK (killer_eye_color IN ('YELLOW', 'ORANGE', 'WHITE')),
    killer_hair_color VARCHAR(16) CHECK (killer_hair_color IN ('YELLOW', 'ORANGE', 'WHITE')),
    CONSTRAINT killer_all_or_nothing CHECK (
        (killer_name IS NULL AND killer_height IS NULL AND killer_eye_color IS NULL AND killer_hair_color IS NULL)
        OR
        (killer_name IS NOT NULL AND killer_height IS NOT NULL AND killer_eye_color IS NOT NULL AND killer_hair_color IS NOT NULL)
    )
);

CREATE TABLE dragon_team (
    id            BIGINT PRIMARY KEY,
    team_name     VARCHAR(255) NOT NULL CHECK (length(team_name) > 0),
    team_size     INTEGER NOT NULL CHECK (team_size > 0),
    start_cave_id BIGINT NOT NULL
);
